const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const base = process.env.SITE_URL || 'http://127.0.0.1:8765/';
  const notebook = new URL('notebook.html', base).href;  // the homepage (index.html) is checked by check_home.cjs
  const output = process.env.SITE_CHECK_OUTPUT || '/tmp/m2s-site-preview/screenshots';
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  const response = await page.goto(notebook, { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  assert.equal(await page.locator('h1').count(), 1);
  assert.equal(await page.locator('h2[id]').count(), 9);
  assert.equal(await page.locator('.study').count(), 11);
  const ids = await page.locator('[id]').evaluateAll(nodes => nodes.map(n => n.id));
  assert.equal(new Set(ids).size, ids.length, 'Duplicate IDs');
  const anchors = await page.locator('a[href^="#"]').evaluateAll(nodes => nodes.map(n => n.hash.slice(1)));
  anchors.forEach(id => assert(ids.includes(id), 'Missing anchor '+id));
  const urls = await page.locator('a[href], img[src], link[href], script[src]').evaluateAll(nodes => [...new Set(nodes.map(n => n.href || n.src).filter(Boolean))]);
  let checkedLinks = 0;
  for (const value of urls) {
    const url = new URL(value);
    if (url.origin !== new URL(base).origin || url.hash) continue;
    const r = await page.request.get(url.href);
    assert(r.ok(), 'Broken local resource: '+url.href);
    checkedLinks++;
  }
  await page.screenshot({ path: path.join(output, 'desktop.png') });
  await page.locator('[data-filter="Generation"]').click();
  assert.equal(await page.locator('.study:visible').count(), 2);
  assert.equal(await page.locator('#filter-status').textContent(), '2 studies');
  await page.locator('[data-filter="All"]').click();
  await page.locator('#study-pilot summary').click();
  assert(await page.locator('#study-pilot details').getAttribute('open') !== null);
  await page.locator('#transport').evaluate(el => { el.value = '90'; el.dispatchEvent(new Event('input', { bubbles:true })); });
  assert.equal(await page.locator('#transport-value').textContent(), '0.90');
  const transportBefore = await page.locator('#transport-plot').innerHTML();
  await page.locator('#physical').evaluate(el => { el.value = '70'; el.dispatchEvent(new Event('input', { bubbles:true })); });
  assert.equal(await page.locator('#physical-value').textContent(), '0.70');
  assert.equal(await page.locator('#transport-plot').innerHTML(), transportBefore);
  await page.locator('#reset-demo').click();
  assert.equal(await page.locator('#transport-value').textContent(), '0.45');
  await page.locator('#flow-demo').screenshot({ path: path.join(output, 'interactive.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(notebook, { waitUntil:'networkidle' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page overflows');
  await page.screenshot({ path:path.join(output, 'mobile.png') });
  await page.locator('[data-filter="Checking"]').click();
  assert.equal(await page.locator('.study:visible').count(), 2);
  const nojs = await browser.newPage({javaScriptEnabled:false});
  await nojs.goto(notebook);
  assert.equal(await nojs.locator('.study').count(), 11);
  assert.equal(errors.length, 0, errors.join('\n'));
  const result = {status:'passed',url:base,chapters:9,studies:11,checkedLocalResources:checkedLinks,desktop:true,mobile:true,noPageOverflow:true,filters:true,details:true,independentClocks:true,reset:true,staticContentWithoutJS:true,consoleErrors:errors};
  fs.writeFileSync(path.join(output,'checks.json'), JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(err => { console.error(err); process.exit(1); });
